def label(sign, bucket):
    return sign * 8 + bucket

def q(sign, bucket):
    return r[bucket] if sign == 1 else 1 - r[bucket]

def q_label(lab):
    return q(lab // 8, lab % 8)

def lit_satisfied(sign, bit):
    return bool(bit) if sign == 1 else not bool(bit)

def g(endpoint_sign, bucket, kind):
    if kind == 'lo':
        return -(1 - L[bucket]) if endpoint_sign == 1 else (1 + L[bucket])
    if kind == 'up':
        return (1 - U[bucket]) if endpoint_sign == 1 else -(1 + U[bucket])
    raise ValueError(kind)

pair_list = [(0, 1), (0, 2), (1, 2)]
pair_to_idx = {p: i for i, p in enumerate(pair_list)}

def idx_const(): return 0

def idx_u(pos, lab): return 1 + pos * 16 + lab

def idx_p(pair, a, b): return 1 + 48 + pair_to_idx[pair] * 256 + a * 16 + b

def idx_lam(bucket, bit, kind):
    k = 0 if kind == 'lo' else 1
    return ((bucket * 2 + bit) * 2 + k)

def H(labels):
    total = components[idx_const()]
    for pos, lab in enumerate(labels):
        total += components[idx_u(pos, lab)]
    for pair in pair_list:
        a, b = pair
        total += components[idx_p(pair, labels[a], labels[b])]
    return total

def h_value(length, signs, buckets):
    if length == 1:
        return q(signs[0], buckets[0])
    if length == 2:
        return 1 - (1 - q(signs[0], buckets[0])) * (1 - q(signs[1], buckets[1]))
    if length == 3:
        return H(tuple(label(s, b) for s, b in zip(signs, buckets)))
    raise ValueError(length)

def endpoint_dual_contribution(length, sign, bucket, bit):
    total = F(0)
    for kind in ['lo', 'up']:
        total += weights[length] * lambdas[idx_lam(bucket, bit, kind)] * g(sign, bucket, kind)
    return total

def main():
    long_floor = 1 - (1 - MIN_LITERAL)**4
    assert long_floor >= rho

    min_upper = None
    min_upper_label = None
    for labels in product(range(16), repeat=3):
        fail = F(1)
        for lab in labels:
            fail *= 1 - q_label(lab)
        true_rounding_value = 1 - fail
        slack = true_rounding_value - H(labels)
        if min_upper is None or slack < min_upper:
            min_upper = slack
            min_upper_label = labels
        assert slack >= 0, (labels, slack, H(labels), true_rounding_value)

    endpoint_cache = {
        (length, sign, bucket, bit): endpoint_dual_contribution(length, sign, bucket, bit)
        for length in [1, 2, 3]
        for sign in [0, 1]
        for bucket in range(8)
        for bit in [0, 1]
    }

    checked = 0
    min_cert = None
    min_atom = None
    for length in [1, 2, 3]:
        for signs in product([0, 1], repeat=length):
            for buckets in product(range(8), repeat=length):
                h = h_value(length, signs, buckets)
                for bits in product([0, 1], repeat=length):
                    opt = F(1) if any(lit_satisfied(s, b) for s, b in zip(signs, bits)) else F(0)
                    cert = h - rho * opt
                    for sign, bucket, bit in zip(signs, buckets, bits):
                        cert += endpoint_cache[(length, sign, bucket, bit)]
                    checked += 1
                    if min_cert is None or cert < min_cert:
                        min_cert = cert
                        min_atom = (length, signs, buckets, bits)
                    assert cert >= 0, (length, signs, buckets, bits, cert)

    print(f'ratio rho: {rho} = {float(rho):.9f}')
    print(f'long-clause floor: {long_floor} = {float(long_floor):.12f}')
    print(f'upper constraints verified: {16**3}; minimum upper slack: {min_upper} at {min_upper_label}')
    print(f'atom inequalities verified: {checked}; minimum certificate slack: {min_cert} at {min_atom}')
    print(f'nonzero H components: {sum(x != 0 for x in components)}')
    print(f'nonzero dual multipliers: {sum(x != 0 for x in lambdas)}')

if __name__ == '__main__':
    main()
