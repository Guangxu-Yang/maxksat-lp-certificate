#!/usr/bin/env python3
"""Sparse search for weighted Max-2SAT snapshot certificates.

This is the follow-up to max2sat_snapshot_certificate_search.py.  It keeps the
same atom certificate, but allows the snapshot bias to use a general unary
weight

    b_v = (w(P_v^{(1)}-N_v^{(1)}) + (P_v^{(2)}-N_v^{(2)}))
          / (w(P_v^{(1)}+N_v^{(1)}) + (P_v^{(2)}+N_v^{(2)})).

Equivalently, in the finite dual LP a unary atom has endpoint weight w/2 while
each binary endpoint has weight 1/2.  The script uses a sparse LP matrix so that
large bucket counts are feasible.
"""

from __future__ import annotations

